#!/usr/bin/env node
/**
 * Prepend the hand-written type header onto napi's generated index.d.ts.
 *
 * napi emits `SqlValue`, `SqlRow` and `NotifyEnvelope` in signatures (via the
 * ts_arg_type / ts_return_type annotations in src/lib.rs) but has no way to
 * DECLARE them: they are TypeScript unions and aliases with no Rust struct to
 * derive from. Without this step the generated declarations reference three
 * types that do not exist, and every consumer's typecheck fails on a dangling
 * name. `--dts-header` is not the hook: it takes literal content, not a path.
 *
 * Idempotent: re-running after a build that already carries the header is a
 * no-op, so it is safe to chain onto every build.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const dts = join(here, "index.d.ts");
const header = readFileSync(join(here, "dts-header.txt"), "utf8");

const MARKER = "export type SqlValue";
const current = readFileSync(dts, "utf8");

if (current.includes(MARKER)) {
  console.log("[dts-header] already present");
} else {
  // Drop napi's own two-line banner; the header carries its own.
  const body = current.replace(/^\/\* auto-generated by NAPI-RS \*\/\n\/\* eslint-disable \*\/\n/, "");
  writeFileSync(dts, `${header}\n${body}`);
  console.log("[dts-header] prepended SqlValue, SqlRow, NotifyEnvelope");
}
